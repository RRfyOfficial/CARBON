#!/usr/bin/env python3
"""CARBON protocol test vectors (protocol/PROTOCOL.md Section 8).

The neutral referee for the link framing: a small reference implementation of PROTOCOL.md
Section 4 that writes the cases both sides must reproduce byte for byte.

    python tools/gen_test_vectors.py

Writes protocol/test-vectors/framing.json (read by the xUnit tests) and the same JSON into
ios/CarbonTests/ProtocolVectors.swift (the Swift tests can't read files outside their bundle).
Standard library only.
"""

import json
import math
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_OUT = ROOT / "protocol" / "test-vectors" / "framing.json"
SWIFT_OUT = ROOT / "ios" / "CarbonTests" / "ProtocolVectors.swift"

HEADER = struct.Struct("<HHH")  # msgId, index, count (little-endian u16)
MAX_MESSAGE = 65_536
MIN_CHUNK, MAX_CHUNK = 14, 506


def split(message: bytes, msg_id: int, chunk: int) -> list[bytes]:
    assert len(message) <= MAX_MESSAGE and MIN_CHUNK <= chunk <= MAX_CHUNK and 0 <= msg_id <= 0xFFFF
    count = max(1, math.ceil(len(message) / chunk))
    return [HEADER.pack(msg_id, i, count) + message[i * chunk:(i + 1) * chunk] for i in range(count)]


def reassemble(frames: list[bytes]) -> list[bytes]:
    """In-order reassembly per msgId (PROTOCOL.md Section 4). The 5 s timeout isn't modelled."""
    partial: dict[int, dict] = {}
    done: list[bytes] = []
    for frame in frames:
        if len(frame) < HEADER.size:
            continue
        msg_id, index, count = HEADER.unpack_from(frame)
        chunk = frame[HEADER.size:]
        if count == 0 or index >= count:
            continue
        if index == 0:
            p = partial[msg_id] = {"count": count, "next": 1, "data": bytearray(chunk)}
        else:
            p = partial.get(msg_id)
            if p is None or p["count"] != count or p["next"] != index:
                partial.pop(msg_id, None)
                continue
            p["data"] += chunk
            p["next"] += 1
        if len(p["data"]) > MAX_MESSAGE:
            partial.pop(msg_id, None)
            continue
        if p["next"] == p["count"]:
            done.append(bytes(p["data"]))
            del partial[msg_id]
    return done


def frame(msg_id: int, index: int, count: int, chunk: bytes) -> bytes:
    return HEADER.pack(msg_id, index, count) + chunk


def clip(text: str, clip_id: str = "0F8C2E2A-5B1D-4C55-9C1E-3D6A0B7E9F10") -> bytes:
    message = {"v": 1, "type": "clip", "id": clip_id, "ts": 1760030000000,
               "mode": "clipboard", "text": text, "html": None}
    return json.dumps(message, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def pattern(n: int) -> bytes:
    return bytes((i * 7 + 3) % 256 for i in range(n))


def split_cases() -> list[dict]:
    cases = [
        ("short clip in one frame", clip("Week 6: Usability Testing"), 1, 180),
        ("exactly two chunks", pattern(360), 2, 180),
        ("uneven last chunk", pattern(400), 3, 180),
        ("empty message", b"", 7, 20),
        ("msgId at the wrap point", b'{"v":1,"type":"ack"}', 0xFFFF, 182),
        ("UTF-8 split mid-character", clip("• Recruit 5 participants · café ✓"), 9, 20),
        ("minimum chunk size", clip("x"), 10, MIN_CHUNK),
        ("maximum chunk size", pattern(1200), 11, MAX_CHUNK),
    ]
    return [{"name": name, "msgId": msg_id, "chunkSize": chunk, "message": message.hex(),
             "frames": [f.hex() for f in split(message, msg_id, chunk)]}
            for name, message, msg_id, chunk in cases]


def reassemble_cases() -> list[dict]:
    a = split(pattern(400), 3, 180)          # 3 frames
    b = split(clip("second message"), 4, 40)  # several frames
    c = split(clip("third"), 5, 30)
    cases = [
        ("frames in order", a),
        ("two messages interleaved", [b[0], a[0], b[1], a[1], a[2]] + b[2:]),
        ("index 0 restarts a msgId", [a[0], a[1], frame(3, 0, 2, b"new "), frame(3, 1, 2, b"message")]),
        ("gap drops the message", [a[0], a[2], a[1]]),
        ("duplicate frame drops the message", [a[0], a[1], a[1], a[2]]),
        ("count change drops the message", [frame(6, 0, 3, b"abc"), frame(6, 1, 2, b"def")]),
        ("bad headers are ignored", [frame(8, 0, 0, b"zero count"), frame(8, 2, 2, b"index past count"),
                                     b"\x01\x00", frame(8, 0, 1, b"ok")]),
        ("single-frame messages", [frame(1, 0, 1, b"one"), frame(2, 0, 1, b""), c[0]] + c[1:]),
    ]
    return [{"name": name, "frames": [f.hex() for f in frames],
             "messages": [m.hex() for m in reassemble(frames)]}
            for name, frames in cases]


def main() -> None:
    vectors = {
        "version": 1,
        "about": "CARBON framing test vectors, generated by tools/gen_test_vectors.py. See protocol/PROTOCOL.md Section 4.",
        "split": split_cases(),
        "reassemble": reassemble_cases(),
    }
    text = json.dumps(vectors, indent=2) + "\n"
    JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.write_text(text, encoding="utf-8", newline="\n")
    swift = (
        "// Generated by tools/gen_test_vectors.py from protocol/test-vectors/framing.json. Don't edit.\n\n"
        "enum ProtocolVectors {\n"
        "    static let framing = #\"\"\"\n"
        f"{text}"
        "\"\"\"#\n"
        "}\n"
    )
    SWIFT_OUT.write_text(swift, encoding="utf-8", newline="\n")
    print(f"wrote {JSON_OUT.relative_to(ROOT)} and {SWIFT_OUT.relative_to(ROOT)}: "
          f"{len(vectors['split'])} split, {len(vectors['reassemble'])} reassemble cases")


if __name__ == "__main__":
    main()
